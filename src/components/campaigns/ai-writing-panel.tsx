"use client"

import { useState } from "react"
import { toast } from "sonner"
import { Loader2, Sparkles, Wand2 } from "lucide-react"
import { Button } from "@/components/ui/button"
import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card"
import { Label } from "@/components/ui/label"
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select"
import { apiFetch, errorMessage } from "@/lib/api-client"
import type { AiGeneratedCopy, AiGeneratedLandingContent } from "@/modules/ai"
import { matchCtaType } from "@/modules/ai/cta"
import { AI_TONES, AI_TONE_LABELS, type AiTone } from "@/modules/ai/schemas"
import { CTA_LABELS } from "@/modules/campaigns/labels"

/**
 * AI writing assistant for the campaign form (Phase 7 tasks 7.1 + 7.2).
 *
 * Content is generated by the configured provider and inserted into the form as
 * editable text. Nothing is saved or published automatically, and the panel is
 * explicit about which deployment provider produced the draft. When no provider
 * is configured the panel explains that instead of inventing copy.
 */

export interface AiWritingPanelValues {
  name: string
  industrySlug: string
  productDetails: string
  offerDetails: string
  targetAudience: string
  targetLocation: string
  priceDisplay: string
}

export interface AiWritingAppliedFields {
  headline?: string
  promoDescription?: string
  productDetails?: string
  offerDetails?: string
  ctaType?: ReturnType<typeof matchCtaType>
}

interface AiWritingPanelProps {
  aiConfigured: boolean
  disabled?: boolean
  /** Reads the live form values so edits made after typing are respected. */
  readForm: () => AiWritingPanelValues
  onApply: (fields: AiWritingAppliedFields) => void
}

interface GenerationMeta {
  provider: string
  model: string
}

type Busy = "copy" | "landing" | null

export function AiWritingPanel({
  aiConfigured,
  disabled = false,
  readForm,
  onApply,
}: AiWritingPanelProps) {
  const [tone, setTone] = useState<AiTone>("professional")
  const [busy, setBusy] = useState<Busy>(null)
  const [meta, setMeta] = useState<GenerationMeta | null>(null)
  const [copy, setCopy] = useState<AiGeneratedCopy | null>(null)
  const [landing, setLanding] = useState<AiGeneratedLandingContent | null>(null)

  async function run(kind: "copy" | "landing") {
    const values = readForm()
    const productDetails = values.productDetails.trim()

    if (productDetails.length < 10) {
      toast.error("Add at least 10 characters of product or service details first.")
      return
    }
    if (kind === "landing" && values.name.trim().length < 2) {
      toast.error("Add a campaign name before generating landing content.")
      return
    }

    setBusy(kind)
    try {
      if (kind === "copy") {
        const response = await apiFetch<{
          data: AiGeneratedCopy
          meta: GenerationMeta
        }>("/api/ai/ad-copy", {
          method: "POST",
          body: JSON.stringify({
            industrySlug: values.industrySlug || undefined,
            productDetails,
            offerDetails: values.offerDetails,
            targetAudience: values.targetAudience,
            tone,
          }),
        })
        setCopy(response.data)
        setLanding(null)
        setMeta(response.meta)
      } else {
        const response = await apiFetch<{
          data: AiGeneratedLandingContent
          meta: GenerationMeta
        }>("/api/ai/landing-content", {
          method: "POST",
          body: JSON.stringify({
            campaignName: values.name,
            industrySlug: values.industrySlug || undefined,
            productDetails,
            offerDetails: values.offerDetails,
            targetAudience: values.targetAudience,
            targetLocation: values.targetLocation,
            priceDisplay: values.priceDisplay,
            tone,
          }),
        })
        setLanding(response.data)
        setCopy(null)
        setMeta(response.meta)
      }
    } catch (error) {
      toast.error(errorMessage(error, "Could not generate content. Please try again."))
    } finally {
      setBusy(null)
    }
  }

  function apply(fields: AiWritingAppliedFields) {
    onApply(fields)
    toast.success("Added to the form — review before saving")
  }

  const cannotGenerate = !aiConfigured || busy !== null || disabled

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-lg">
          <Sparkles className="size-5 text-primary" aria-hidden /> AI writing assistant
        </CardTitle>
        <CardDescription>
          Draft promotional copy from the details you enter. Nothing is saved or published
          automatically — review and edit every line before you save.
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-4">
        {!aiConfigured ? (
          <p className="rounded-md bg-muted px-3 py-2 text-sm text-muted-foreground">
            AI content generation is not configured on this deployment, so no drafts can be
            produced. The campaign review, lead qualification and follow-up suggestions still
            work — they are rule-based and use only your own campaign and lead data.
          </p>
        ) : (
          <>
            <div className="flex flex-wrap items-end gap-3">
              <div className="space-y-1.5">
                <Label htmlFor="ai-tone">Tone</Label>
                <Select
                  value={tone}
                  onValueChange={(value) => setTone(value as AiTone)}
                  disabled={busy !== null || disabled}
                >
                  <SelectTrigger id="ai-tone" className="w-40">
                    <SelectValue placeholder="Choose a tone" />
                  </SelectTrigger>
                  <SelectContent>
                    {AI_TONES.map((option) => (
                      <SelectItem key={option} value={option}>
                        {AI_TONE_LABELS[option]}
                      </SelectItem>
                    ))}
                  </SelectContent>
                </Select>
              </div>

              <Button
                type="button"
                variant="outline"
                onClick={() => run("copy")}
                disabled={cannotGenerate}
              >
                {busy === "copy" ? (
                  <Loader2 className="size-4 animate-spin" aria-hidden />
                ) : (
                  <Wand2 className="size-4" aria-hidden />
                )}
                {busy === "copy" ? "Drafting…" : "Generate ad copy"}
              </Button>

              <Button
                type="button"
                onClick={() => run("landing")}
                disabled={cannotGenerate}
              >
                {busy === "landing" ? (
                  <Loader2 className="size-4 animate-spin" aria-hidden />
                ) : (
                  <Sparkles className="size-4" aria-hidden />
                )}
                {busy === "landing" ? "Drafting…" : "Generate landing content"}
              </Button>
            </div>

            <p className="text-xs text-muted-foreground">
              Fill in “Product or service details” first. The assistant uses only the facts you
              provide and never adds statistics, awards or guarantees.
            </p>
          </>
        )}

        {copy && (
          <div className="space-y-4 border-t border-border pt-4">
            <section className="space-y-2">
              <h3 className="text-sm font-medium">Headlines</h3>
              <ul className="space-y-2">
                {copy.headlines.map((headline) => (
                  <li
                    key={headline}
                    className="flex items-start justify-between gap-3 rounded-md border border-border px-3 py-2"
                  >
                    <span className="text-sm leading-relaxed">{headline}</span>
                    <Button
                      type="button"
                      size="sm"
                      variant="ghost"
                      onClick={() => apply({ headline })}
                    >
                      Use
                    </Button>
                  </li>
                ))}
              </ul>
            </section>

            <section className="space-y-2">
              <h3 className="text-sm font-medium">Descriptions</h3>
              <ul className="space-y-2">
                {copy.descriptions.map((description) => (
                  <li
                    key={description}
                    className="space-y-2 rounded-md border border-border px-3 py-2"
                  >
                    <p className="text-sm leading-relaxed whitespace-pre-line">
                      {description}
                    </p>
                    <Button
                      type="button"
                      size="sm"
                      variant="ghost"
                      onClick={() => apply({ promoDescription: description })}
                    >
                      Use as promotional description
                    </Button>
                  </li>
                ))}
              </ul>
            </section>

            <section className="space-y-2">
              <h3 className="text-sm font-medium">Call-to-action ideas</h3>
              <ul className="space-y-2">
                {copy.suggestedCtas.map((cta) => {
                  const matched = matchCtaType(cta)
                  return (
                    <li
                      key={cta}
                      className="flex items-center justify-between gap-3 rounded-md border border-border px-3 py-2"
                    >
                      <span className="text-sm">{cta}</span>
                      {matched ? (
                        <Button
                          type="button"
                          size="sm"
                          variant="ghost"
                          onClick={() => apply({ ctaType: matched })}
                        >
                          Use “{CTA_LABELS[matched]}”
                        </Button>
                      ) : (
                        <span className="text-xs text-muted-foreground">
                          No matching button type
                        </span>
                      )}
                    </li>
                  )
                })}
              </ul>
            </section>

            {meta && (
              <p className="text-xs text-muted-foreground">
                Drafted with {meta.provider} ({meta.model}). Check every claim before
                publishing.
              </p>
            )}
          </div>
        )}

        {landing && (
          <div className="space-y-3 border-t border-border pt-4">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <h3 className="text-sm font-medium">Suggested landing-page content</h3>
              <Button
                type="button"
                size="sm"
                onClick={() =>
                  apply({
                    headline: landing.headline,
                    promoDescription: landing.promoDescription,
                    productDetails: landing.productDetails.trim() || undefined,
                    offerDetails: landing.offerDetails.trim() || undefined,
                    ctaType: landing.suggestedCta ?? undefined,
                  })
                }
              >
                Use all
              </Button>
            </div>

            <dl className="space-y-3 text-sm">
              <div className="space-y-1">
                <dt className="text-xs font-medium text-muted-foreground">Headline</dt>
                <dd className="leading-relaxed">{landing.headline}</dd>
              </div>
              <div className="space-y-1">
                <dt className="text-xs font-medium text-muted-foreground">
                  Promotional description
                </dt>
                <dd className="whitespace-pre-line leading-relaxed">
                  {landing.promoDescription}
                </dd>
              </div>
              {landing.productDetails.trim() && (
                <div className="space-y-1">
                  <dt className="text-xs font-medium text-muted-foreground">
                    Product or service details
                  </dt>
                  <dd className="whitespace-pre-line leading-relaxed">
                    {landing.productDetails}
                  </dd>
                </div>
              )}
              {landing.offerDetails.trim() && (
                <div className="space-y-1">
                  <dt className="text-xs font-medium text-muted-foreground">Offer details</dt>
                  <dd className="whitespace-pre-line leading-relaxed">
                    {landing.offerDetails}
                  </dd>
                </div>
              )}
              {landing.suggestedCtaLabel.trim() && (
                <div className="space-y-1">
                  <dt className="text-xs font-medium text-muted-foreground">
                    Suggested call to action
                  </dt>
                  <dd>
                    {landing.suggestedCta
                      ? CTA_LABELS[landing.suggestedCta]
                      : `${landing.suggestedCtaLabel} (does not match a configured button type)`}
                  </dd>
                </div>
              )}
            </dl>

            {meta && (
              <p className="text-xs text-muted-foreground">
                Drafted with {meta.provider} ({meta.model}). Check every claim before
                publishing.
              </p>
            )}
          </div>
        )}
      </CardContent>
    </Card>
  )
}
