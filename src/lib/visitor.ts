/**
 * First-party visitor identity for landing-page analytics.
 *
 * A random id is stored in a first-party cookie by the public landing page and
 * sent with page-view beacons. It is not a login, contains no personal data and
 * is only used to count unique visitors and attribute an enquiry to the visit
 * that produced it. Enquiries still work when cookies are blocked — they simply
 * are not attributed to a tracked visit.
 */

export const VISITOR_COOKIE = "ch_visitor"

/** One year, in seconds. */
export const VISITOR_COOKIE_MAX_AGE = 365 * 24 * 60 * 60

/** UUIDs satisfy this; so do other opaque ids generated by clients. */
const VISITOR_ID_PATTERN = /^[A-Za-z0-9_-]{8,64}$/

export function isValidVisitorId(value: string): boolean {
  return VISITOR_ID_PATTERN.test(value)
}

/** Reads one cookie from a raw `Cookie` header without booting a cookie parser. */
export function readCookieValue(cookieHeader: string | null, name: string): string | null {
  if (!cookieHeader) return null
  for (const part of cookieHeader.split(";")) {
    const [key, ...rest] = part.trim().split("=")
    if (key === name) {
      const value = rest.join("=").trim()
      return value || null
    }
  }
  return null
}
